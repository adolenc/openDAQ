        /// <summary>Writes both headers and returns their paths.</summary>
        /// <param name="bindingsRoot">Root of the bindings, holding "include" and "src".</param>
        /// <param name="options">Options of the running generator.</param>
        /// <param name="coreRoot">Root of the core sources.</param>
        public static IList<string> Write(string bindingsRoot, IGeneratorOptions options, string coreRoot)
        {
            JsonConfigGenerator linker = new JsonConfigGenerator { Options = (IGeneratorOptions) options.Clone() };
            OrderedDict api = linker.BuildApi(coreRoot, out _);

            string enums = Path.Combine(bindingsRoot, "include", "cenums.h");
            string errors = Path.Combine(bindingsRoot, "include", "cerrors.h");
            File.WriteAllText(enums, GetEnums(api), new UTF8Encoding(false));
            File.WriteAllText(errors, GetStatusCodes(api), new UTF8Encoding(false));
            return new[] { enums, errors };
        }

        private static string GetEnums(OrderedDict api)
        {
            StringBuilder sb = new StringBuilder(Banner);
            sb.AppendLine();
            sb.AppendLine("#ifdef __cplusplus");
            sb.AppendLine("extern \"C\"");
            sb.AppendLine("{");
            sb.AppendLine("#endif");

            foreach (OrderedDict enumeration in api.GetList("enums").OfType<OrderedDict>())
            {
                string name = enumeration.GetString("c_name");
                List<OrderedDict> options = enumeration.GetList("options").OfType<OrderedDict>().ToList();

                sb.AppendLine();
                sb.AppendLine($"    typedef enum {name}");
                sb.AppendLine("    {");
                for (int i = 0; i < options.Count; i++)
                {
                    // An option the core spells as an expression has no value in the description.
                    object value = options[i].Get("value") ?? options[i].Get("raw_value");
                    string separator = i == options.Count - 1 ? "" : ",";
                    sb.AppendLine($"        {options[i].GetString("c_name")} = {value}{separator}");
                }
                sb.AppendLine($"    }} {name};");
            }

            sb.AppendLine();
            sb.AppendLine("#ifdef __cplusplus");
            sb.AppendLine("}");
            sb.AppendLine("#endif");
            return sb.ToString();
        }

        private static string GetStatusCodes(OrderedDict api)
        {
            StringBuilder sb = new StringBuilder(Banner);
            sb.AppendLine();
            sb.AppendLine("/* A status code is an error when its highest bit is set. */");
            sb.AppendLine("#define DAQ_ERROR_CODE(TYPE_ID, ERROR_CODE) (0x80000000u | ((TYPE_ID) << 16u) | (ERROR_CODE))");
            sb.AppendLine("#define DAQ_GET_ERROR_CODE(ERROR) (0x0000FFFFu & (ERROR))");
            sb.AppendLine("#define DAQ_FAILED(x)    ((x) & 0x80000000u)");
            sb.AppendLine("#define DAQ_SUCCEEDED(x) (!DAQ_FAILED(x))");
            sb.AppendLine();

            List<OrderedDict> codes = api.GetList("error_codes").OfType<OrderedDict>().ToList();
            List<string> names = codes.Select(c => GetStatusName(c.GetString("name"))).ToList();
            int width = names.Max(n => n.Length);
            for (int i = 0; i < codes.Count; i++)
            {
                long code = Convert.ToInt64(codes[i].Get("code"));
                sb.AppendLine($"#define {names[i].PadRight(width)} 0x{code:X8}u");
            }
            return sb.ToString();
        }

        /// <summary>The core prefixes its status codes with "OPENDAQ_", the C bindings with "DAQ_".</summary>
        private static string GetStatusName(string coreName)
        {
            const string corePrefix = "OPENDAQ_";
            return coreName.StartsWith(corePrefix, StringComparison.Ordinal)
                       ? "DAQ_" + coreName.Substring(corePrefix.Length)
                       : coreName;
        }
    }
